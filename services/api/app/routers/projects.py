@router.get("/{project_id}/jobs/{job_id}/outputs")
async def get_job_outputs(
    project_id: UUID,
    job_id: UUID,
    limit: int = 50,
    offset: int = 0,
    db: AsyncSession = Depends(get_db)
):
    pid = str(project_id)
    jid = str(job_id)
    
    outputs_res = await db.execute(
        text("""
            SELECT id, project_id, canonical_content_id, generation_job_id, output_type, title, content, status, metadata, media, created_at, updated_at 
            FROM generated_outputs 
            WHERE project_id = :pid AND generation_job_id = :jid
            ORDER BY created_at DESC
            LIMIT :limit OFFSET :offset
        """), 
        {"pid": pid, "jid": jid, "limit": limit, "offset": offset}
    )
    rows = outputs_res.mappings().all()
    
    def serialize(item):
        d = dict(item)
        for k, v in d.items():
            if hasattr(v, "isoformat"):
                d[k] = v.isoformat()
            elif isinstance(v, UUID):
                d[k] = str(v)
                
        # Generate presigned URL for top-level media
        if d.get("media") and isinstance(d["media"], list):
            for m in d["media"]:
                if isinstance(m, dict) and m.get("storage_path"):
                    try:
                        m["url"] = storage_service.generate_presigned_download_url(m["storage_path"])
                    except Exception as e:
                        logger.error(f"Failed to generate presigned URL for top media: {e}")

        if d.get("metadata") and isinstance(d["metadata"], dict):
            # Backward compatibility for old structure
            if d["metadata"].get("media"):
                for m in d["metadata"]["media"]:
                    if m.get("storage_path"):
                        try:
                            m["url"] = storage_service.generate_presigned_download_url(m["storage_path"])
                        except Exception as e:
                            logger.error(f"Failed to generate presigned URL for metadata media: {e}")
                            
            # New nested structure for slides
            if d["metadata"].get("slides") and isinstance(d["metadata"]["slides"], list):
                for slide in d["metadata"]["slides"]:
                    if isinstance(slide, dict) and slide.get("image") and isinstance(slide["image"], dict):
                        if slide["image"].get("storage_path"):
                            try:
                                slide["image"]["url"] = storage_service.generate_presigned_download_url(slide["image"]["storage_path"])
                            except Exception as e:
                                logger.error(f"Failed to generate presigned URL for slide image: {e}")
        return d

    # Group by output_type
    grouped = {}
    for row in rows:
        d = serialize(row)
        t = d["output_type"]
        if t not in grouped:
            grouped[t] = []
        grouped[t].append(d)
        
    return {"outputs": grouped}


@router.get("/{project_id}/workspace")
async def get_project_workspace(project_id: UUID, db: AsyncSession = Depends(get_db)):
    """Get the full workspace state for a project."""
    
    pid = str(project_id)
    
    # 1. Project
    proj_res = await db.execute(
        text("SELECT * FROM projects WHERE id = :id"), {"id": pid}
    )
    project = proj_res.mappings().first()
    if not project:
        raise HTTPException(status_code=404, detail="Project not found")
        
    # 2. Sources
    sources_res = await db.execute(
        text("SELECT * FROM sources WHERE project_id = :pid ORDER BY created_at DESC"), {"pid": pid}
    )
    sources = [dict(row) for row in sources_res.mappings().all()]
    
    # 3. Uploads
    uploads_res = await db.execute(
        text("SELECT * FROM uploads WHERE project_id = :pid ORDER BY created_at DESC"), {"pid": pid}
    )
    uploads = [dict(row) for row in uploads_res.mappings().all()]
    
    # 4. Media
    media_res = await db.execute(
        text("SELECT * FROM media WHERE project_id = :pid ORDER BY created_at DESC"), {"pid": pid}
    )
    media = [dict(row) for row in media_res.mappings().all()]
    
    # 5. Transcripts
    transcripts_res = await db.execute(
        text("SELECT * FROM transcripts WHERE project_id = :pid ORDER BY created_at DESC"), {"pid": pid}
    )
    transcripts = [dict(row) for row in transcripts_res.mappings().all()]
    
    # 6. Canonical Contents
    canonical_res = await db.execute(
        text("SELECT * FROM canonical_contents WHERE project_id = :pid ORDER BY created_at DESC"), {"pid": pid}
    )
    canonical = [dict(row) for row in canonical_res.mappings().all()]
    
    # 7. Generated Outputs (Metadata Only)
    generated_res = await db.execute(
        text("SELECT id, project_id, canonical_content_id, output_type, platform, title, status, metadata, created_at, updated_at FROM generated_outputs WHERE project_id = :pid ORDER BY created_at DESC"), {"pid": pid}
    )
    generated = [dict(row) for row in generated_res.mappings().all()]
    
    # 8. Generation Drafts
    drafts_res = await db.execute(
        text("SELECT * FROM generation_drafts WHERE project_id = :pid"), {"pid": pid}
    )
    draft = drafts_res.mappings().first()
    
    # 9. Generation Jobs
    jobs_res = await db.execute(
        text("SELECT * FROM generation_jobs WHERE project_id = :pid ORDER BY created_at DESC"), {"pid": pid}
    )
    jobs = [dict(row) for row in jobs_res.mappings().all()]
    
    # 10. Processing Usage
    usage_res = await db.execute(
        text("SELECT * FROM processing_usage WHERE project_id = :pid ORDER BY created_at DESC"), {"pid": pid}
    )
    processing_usage = [dict(row) for row in usage_res.mappings().all()]

    # 11. Downloads
    downloads_res = await db.execute(
        text("""
            SELECT d.* FROM downloads d 
            JOIN sources s ON d.source_id = s.id 
            WHERE s.project_id = :pid ORDER BY d.started_at DESC
        """), {"pid": pid}
    )
    downloads = [dict(row) for row in downloads_res.mappings().all()]

    # 12. Webhook Events
    webhooks_res = await db.execute(
        text("""
            SELECT w.id, w.event_type, w.status, w.attempts, w.created_at, w.updated_at, w.last_error, w.payload
            FROM webhook_events w
            LEFT JOIN uploads u ON w.upload_id = u.id
            LEFT JOIN sources s ON w.source_id = s.id
            WHERE u.project_id = :pid 
               OR s.project_id = :pid 
               OR w.payload->'data'->>'project_id' = CAST(:pid AS TEXT)
            ORDER BY w.created_at DESC
        """), {"pid": pid}
    )
    webhook_events = [dict(row) for row in webhooks_res.mappings().all()]
    
    # Convert all UUIDs and datetimes to strings
    def serialize(item):
        for k, v in item.items():
            if hasattr(v, "isoformat"):
                item[k] = v.isoformat()
            elif isinstance(v, UUID):
                item[k] = str(v)
        return item
        
    return {
        "project": serialize(dict(project)),
        "sources": [serialize(s) for s in sources],
        "uploads": [serialize(u) for u in uploads],
        "media": [serialize(m) for m in media],
        "transcripts": [serialize(t) for t in transcripts],
        "canonical_contents": [serialize(c) for c in canonical],
        "generated_outputs": [serialize(g) for g in generated],
        "generation_draft": serialize(dict(draft)) if draft else None,
        "generation_jobs": [serialize(j) for j in jobs],
        "processing_usage": [serialize(pu) for pu in processing_usage],
        "downloads": [serialize(d) for d in downloads],
        "webhook_events": [serialize(we) for we in webhook_events]
    }


@router.delete("/{project_id}")
async def delete_project(
    project_id: UUID, 
    background_tasks: BackgroundTasks,
    db: AsyncSession = Depends(get_db)
):
    """Hard delete a project, cascading to all related records, and remove storage synchronously."""
    pid = str(project_id)
    
    # Check project status
    proj_res = await db.execute(
        text("SELECT status FROM projects WHERE id = :id"), {"id": pid}
    )
    project = proj_res.mappings().first()
    if not project:
        raise HTTPException(status_code=404, detail="Project not found")
        
    if project["status"] == "PROCESSING":
        raise HTTPException(status_code=400, detail="Cannot delete a project currently in PROCESSING state")
        
    # Synchronous storage cleanup BEFORE commit
    prefix = f"projects/{project_id}/"
    logger.info(f"Starting synchronous storage cleanup for prefix: {prefix}")
    try:
        import asyncio
        loop = asyncio.get_event_loop()
        await loop.run_in_executor(None, storage_service.delete_objects_by_prefix, prefix)
    except Exception as e:
        logger.error(f"Storage cleanup failed for project {project_id}: {e}")
        # Storage deletion failed, abort so database remains consistent
        raise HTTPException(status_code=500, detail="Failed to delete project files from storage. Database deletion aborted.")
        
    # Delete jobs explicitly to handle 'ON DELETE SET NULL' constraint and avoid orphans
    await db.execute(
        text("DELETE FROM jobs WHERE project_id = :id"), {"id": pid}
    )
    
    # Hard delete project (Postgres ON DELETE CASCADE will handle the rest)
    await db.execute(
        text("DELETE FROM projects WHERE id = :id"), {"id": pid}
    )
    await db.commit()
    
    return {"message": "Project permanently deleted successfully"}



class ProjectRename(BaseModel):
    name: str

@router.patch("/{project_id}")
async def rename_project(
    project_id: UUID,
    payload: ProjectRename,
    db: AsyncSession = Depends(get_db)
):
    """Rename a project."""
    pid = str(project_id)
    result = await db.execute(
        text("UPDATE projects SET name = :name, updated_at = NOW() WHERE id = :id RETURNING id"),
        {"name": payload.name, "id": pid}
    )
    if not result.first():
        raise HTTPException(status_code=404, detail="Project not found")
        
    await db.commit()
    return {"message": "Project renamed successfully"}
