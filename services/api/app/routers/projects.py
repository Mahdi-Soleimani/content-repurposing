@router.post("/{project_id}/canonical", status_code=201)
async def create_canonical(
    project_id: UUID,
    payload: CanonicalCreate,
    db: AsyncSession = Depends(get_db)
):
    """
    Save canonical content generated by n8n.
    [INTERNAL API] - Intended to be called by n8n webhooks after generation.
    """
    pid = str(project_id)
    job_id = str(payload.generation_job_id)
    import json
    
    # Extract title from content if it's a dict
    title = None
    content_str = payload.content if isinstance(payload.content, str) else ""
    if isinstance(payload.content, dict):
        content_str = json.dumps(payload.content, ensure_ascii=False)
        canon_rep = payload.content.get("canonical_representation", {})
        if isinstance(canon_rep, dict):
            title = canon_rep.get("title")
    
    # Validate job belongs to project
    job_res = await db.execute(
        text("SELECT id FROM generation_jobs WHERE id = :job_id AND project_id = :pid"),
        {"job_id": job_id, "pid": pid}
    )
    if not job_res.first():
        raise HTTPException(status_code=404, detail="Generation job not found or does not belong to project")
        
    result = await db.execute(
        text("""
            INSERT INTO canonical_contents (project_id, title, content, metadata)
            VALUES (:project_id, :title, :content, CAST(:metadata AS jsonb))
            RETURNING id
        """),
        {
            "project_id": pid,
            "title": title,
            "content": content_str,
            "metadata": json.dumps(payload.metadata)
        }
    )
    row = result.first()
    if not row:
        raise HTTPException(status_code=500, detail="Failed to save canonical content")
        
    canonical_id = str(row[0])
    
    # Update generation_jobs with canonical_content_id and mark as PROCESSING
    await db.execute(
        text("UPDATE generation_jobs SET canonical_content_id = :canonical_id, status = 'PROCESSING', started_at = NOW() WHERE id = :job_id"),
        {"canonical_id": canonical_id, "job_id": job_id}
    )
    
    await db.commit()
    return {"message": "Canonical content saved successfully", "id": canonical_id}

async def check_job_completion(job_id: str, db: AsyncSession) -> tuple[int, int]:
    """
    Checks if all requested outputs for a job have been generated.
    If so, marks the generation_job as COMPLETED.
    Returns (completed_count, total_requested_count).
    """
    job_res = await db.execute(
        text("SELECT requested_outputs, status FROM generation_jobs WHERE id = :job_id"),
        {"job_id": job_id}
    )
    job_row = job_res.mappings().first()
    if not job_row:
        return 0, 0
        
    requested_outputs = job_row["requested_outputs"] or {}
    
    counts_res = await db.execute(
        text("""
            SELECT output_type, COUNT(*) as count 
            FROM generated_outputs 
            WHERE generation_job_id = :job_id 
            GROUP BY output_type
        """),
        {"job_id": job_id}
    )
    
    actual_counts = {row.output_type: row.count for row in counts_res}
    
    total_requested = 0
    total_completed = 0
    all_completed = True
    
    for o_type, req_count in requested_outputs.items():
        req_count = int(req_count)
        if req_count <= 0:
            continue
        total_requested += req_count
        act_count = actual_counts.get(o_type, 0)
        total_completed += min(act_count, req_count) # don't over-count if they generated extra
        if act_count < req_count:
            all_completed = False
            
    if all_completed and total_requested > 0 and job_row["status"] != "COMPLETED":
        await db.execute(
            text("UPDATE generation_jobs SET status = 'COMPLETED', completed_at = NOW() WHERE id = :job_id"),
            {"job_id": job_id}
        )
        # Assuming caller manages transaction/commit
        
    return total_completed, total_requested


@router.post("/{project_id}/jobs/{job_id}/outputs", status_code=201)
async def create_output(
    project_id: UUID,
    job_id: UUID,
    payload: OutputCreate,
    db: AsyncSession = Depends(get_db)
):
    """
    [INTERNAL n8n CALLBACK] Initialize generated output from n8n.
    """
    pid = str(project_id)
    canon_id = str(payload.canonical_content_id)
    jid = str(job_id)
    import json
    
    canon_res = await db.execute(
        text("SELECT id FROM canonical_contents WHERE id = :canon_id AND project_id = :pid"),
        {"canon_id": canon_id, "pid": pid}
    )
    if not canon_res.first():
        raise HTTPException(status_code=404, detail="Canonical content not found or does not belong to project")
        
    job_res = await db.execute(
        text("SELECT id FROM generation_jobs WHERE id = :jid AND project_id = :pid"),
        {"jid": jid, "pid": pid}
    )
    if not job_res.first():
        raise HTTPException(status_code=404, detail="Generation job not found or does not belong to project")
        
    result = await db.execute(
        text("""
            INSERT INTO generated_outputs (project_id, canonical_content_id, generation_job_id, output_type, title, content, metadata, media, status)
            VALUES (:project_id, :canon_id, :job_id, :type, :title, :content, CAST(:metadata AS jsonb), CAST(:media AS jsonb), :status)
            RETURNING id
        """),
        {
            "project_id": pid,
            "canon_id": canon_id,
            "job_id": jid,
            "type": payload.output_type,
            "title": payload.title,
            "content": payload.content,
            "metadata": json.dumps(payload.metadata),
            "media": json.dumps(payload.media),
            "status": payload.status
        }
    )
    row = result.first()
    if not row:
        raise HTTPException(status_code=500, detail="Failed to save output")
        
    # Check if job is fully completed
    completed_count, total_count = await check_job_completion(jid, db)
        
    await db.commit()
    
    return {
        "message": "Output initialized successfully", 
        "output_id": str(row[0]), 
        "generation_job_id": jid, 
        "status": payload.status,
        "progress": {
            "completed": completed_count,
            "total": total_count
        }
    }


@router.patch("/{project_id}/jobs/{job_id}/outputs/{output_id}")
async def update_output(
    project_id: UUID,
    job_id: UUID,
    output_id: UUID,
    payload: OutputUpdate,
    db: AsyncSession = Depends(get_db)
):
    """
    [INTERNAL n8n CALLBACK] Incrementally update an existing output (e.g. adding slides as they finish).
    """
    import json
    pid = str(project_id)
    jid = str(job_id)
    oid = str(output_id)
    
    # Get current row
    res = await db.execute(
        text("SELECT metadata, media FROM generated_outputs WHERE id = :oid AND project_id = :pid AND generation_job_id = :jid"),
        {"oid": oid, "pid": pid, "jid": jid}
    )
    row = res.first()
    if not row:
        raise HTTPException(status_code=404, detail="Output not found")
        
    current_metadata = row.metadata if row.metadata else {}
    current_media = row.media if row.media else []
    
    # Merge payload
    updates = {}
    if payload.status is not None:
        updates["status"] = payload.status
    if payload.title is not None:
        updates["title"] = payload.title
    if payload.content is not None:
        updates["content"] = payload.content
    if payload.media is not None:
        # Replace media
        updates["media"] = payload.media
    if payload.metadata is not None:
        if "slide" in payload.metadata:
            slide_to_add = payload.metadata["slide"]
            if "slides" not in current_metadata or not isinstance(current_metadata["slides"], list):
                current_metadata["slides"] = []
            
            # Check if slide index exists
            slide_index = slide_to_add.get("index")
            found = False
            for i, s in enumerate(current_metadata["slides"]):
                if s.get("index") == slide_index:
                    current_metadata["slides"][i].update(slide_to_add)
                    found = True
                    break
            if not found:
                current_metadata["slides"].append(slide_to_add)
                
            # Remove "slide" from the metadata payload so it doesn't get saved as a top-level key
            del payload.metadata["slide"]

        # Shallow merge the rest of the metadata
        current_metadata.update(payload.metadata)
        updates["metadata"] = current_metadata
        
    if not updates:
        return {"message": "No updates provided"}
        
    set_clauses = []
    params = {"oid": oid}
    for k, v in updates.items():
        if k in ["metadata", "media"]:
            set_clauses.append(f"{k} = CAST(:{k} AS jsonb)")
            params[k] = json.dumps(v)
        else:
            set_clauses.append(f"{k} = :{k}")
            params[k] = v
            
    set_clauses.append("updated_at = NOW()")
    set_query = ", ".join(set_clauses)
    
    await db.execute(
        text(f"UPDATE generated_outputs SET {set_query} WHERE id = :oid"),
        params
    )
    await db.commit()
    
    return {"message": "Output updated successfully"}


@router.post("/{project_id}/jobs/{job_id}/outputs/media", status_code=201)
async def upload_output_media(
    project_id: UUID,
    job_id: UUID,
    file: UploadFile = File(...),
    db: AsyncSession = Depends(get_db)
):
    """
    [INTERNAL n8n CALLBACK] Upload media generated by n8n (e.g. images for carousels).
    Returns the storage_path to be used in output metadata.
    """
    import uuid
    from app.config import settings
    
    pid = str(project_id)
    jid = str(job_id)
    
    job_res = await db.execute(
        text("SELECT id FROM generation_jobs WHERE id = :jid AND project_id = :pid"),
        {"jid": jid, "pid": pid}
    )
    if not job_res.first():
        raise HTTPException(status_code=404, detail="Generation job not found or does not belong to project")
    
    
    ext = file.filename.split('.')[-1] if '.' in file.filename else 'bin'
    file_id = str(uuid.uuid4())
    object_key = f"projects/{project_id}/jobs/{job_id}/outputs/media/{file_id}.{ext}"
    
    try:
        storage_service.client.upload_fileobj(
            file.file,
            settings.S3_BUCKET_NAME,
            object_key,
            ExtraArgs={"ContentType": file.content_type}
        )
    except Exception as e:
        logger.error(f"Failed to upload media to S3: {e}")
        raise HTTPException(status_code=500, detail="Failed to upload file")
        
    return {"storage_path": object_key}


